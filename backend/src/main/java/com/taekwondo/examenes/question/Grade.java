package com.taekwondo.examenes.question;

/**
 * Grado de una pregunta: el cinturón mínimo desde el que es apropiada (RF-43).
 * Once posiciones, de blanco a negro, contando los medios cinturones; el orden
 * de declaración es el orden de los grados.
 */
public enum Grade {
    BLANCO,
    BLANCO_AMARILLO,
    AMARILLO,
    AMARILLO_VERDE,
    VERDE,
    VERDE_AZUL,
    AZUL,
    AZUL_ROJO,
    ROJO,
    ROJO_NEGRO,
    NEGRO
}
