-- RF-51: un profesor comparte su examen con otros. El invitado acepta o rechaza; al aceptar consulta
-- el mismo examen (no una copia) y todos sus resultados, pero no puede cambiarlo. Rechazar, cancelar
-- la invitación, retirar el acceso o dejar de verlo borran la fila: así se puede volver a invitar.
create table exam_shares (
    id           bigint generated by default as identity primary key,
    exam_id      bigint       not null references exams (id) on delete cascade,
    teacher_id   bigint       not null references users (id),
    invited_by   bigint       not null references users (id),
    status       varchar(20)  not null check (status in ('PENDING', 'ACCEPTED')),
    created_at   timestamp(6) not null,
    responded_at timestamp(6),
    unique (exam_id, teacher_id)
);
create index idx_exam_shares_teacher on exam_shares (teacher_id, status);
