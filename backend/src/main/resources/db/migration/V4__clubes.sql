-- Clubes (RF-38 a RF-42): cada usuario pertenece como mucho a uno, o a ninguno.

create table clubs (
    id         bigint generated by default as identity primary key,
    name       varchar(100) not null,
    created_at timestamp(6) not null
);

-- Nombre único sin distinguir mayúsculas
create unique index uk_clubs_name on clubs (lower(name));

-- Si se borra un club, sus miembros se quedan sin club
alter table users add column club_id bigint references clubs (id) on delete set null;
create index idx_users_club on users (club_id);
