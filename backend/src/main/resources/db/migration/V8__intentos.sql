-- RF-52: el profesor fija cuántos intentos tiene cada alumno (1 por defecto, como hasta ahora).
alter table exams add column max_attempts integer not null default 1
    check (max_attempts between 1 and 20);

-- DE-04: cada intento queda registrado en el servidor, con quién lo hace y cuándo empezó.
-- Un intento sin entregar y fuera de plazo cuenta como gastado.
create table exam_attempts (
    id              bigint generated by default as identity primary key,
    exam_id         bigint       not null references exams (id),
    student_user_id bigint       references users (id),
    student_name    varchar(100) not null,
    student_club    varchar(100),
    student_email   varchar(200),
    started_at      timestamp(6) not null,
    submitted_at    timestamp(6)
);
create index idx_exam_attempts_exam on exam_attempts (exam_id);
create index idx_exam_attempts_student on exam_attempts (student_user_id);

-- Cada entrega anterior fue un intento entregado: así siguen contando
insert into exam_attempts (exam_id, student_user_id, student_name, student_club, student_email,
                           started_at, submitted_at)
select exam_id, student_user_id, student_name, student_club, student_email,
       completed_at - make_interval(secs => time_spent_seconds), completed_at
from results;
