-- DE-03: al publicar, el examen guarda una copia de sus preguntas. Los intentos y la
-- corrección usan esta copia, así que editar el banco después no cambia el examen.

create table published_questions (
    id             bigint generated by default as identity primary key,
    exam_id        bigint        not null references exams (id) on delete cascade,
    position       integer       not null,
    -- Pregunta del banco de la que sale la copia; sin FK, la copia no depende de ella
    question_id    bigint        not null,
    text           varchar(1000) not null,
    correct_answer integer       not null,
    explanation    varchar(2000),
    constraint uk_published_questions_position unique (exam_id, position)
);

create table published_question_options (
    published_question_id bigint       not null references published_questions (id) on delete cascade,
    option_order          integer      not null,
    option_text           varchar(500) not null,
    primary key (published_question_id, option_order)
);

-- Los exámenes ya publicados o cerrados copian sus preguntas tal como están hoy
insert into published_questions (exam_id, position, question_id, text, correct_answer, explanation)
select eq.exam_id, eq.position, q.id, q.text, q.correct_answer, q.explanation
from exam_questions eq
         join exams e on e.id = eq.exam_id
         join questions q on q.id = eq.question_id
where e.status <> 'DRAFT';

insert into published_question_options (published_question_id, option_order, option_text)
select pq.id, qo.option_order, qo.option_text
from published_questions pq
         join question_options qo on qo.question_id = pq.question_id;
